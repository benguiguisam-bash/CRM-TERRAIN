const DICTS = { fr, en, ru, ro, tr, ku };
const KEY = 'crm-terrain-langue';

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICTS[saved]) return saved;
  } catch { /* stockage indisponible : on détecte */ }
  const nav = (navigator.language || 'fr').slice(0, 2).toLowerCase();
  if (nav === 'mo') return 'ro';
  return DICTS[nav] ? nav : 'fr';
}

let current = detect();
document.documentElement.lang = current === 'ro' ? 'ro-MD' : current;

export function lang() { return current; }

export function setLang(id) {
  if (!DICTS[id]) return;
  current = id;
  document.documentElement.lang = id === 'ro' ? 'ro-MD' : id;
  try { localStorage.setItem(KEY, id); } catch { /* sans stockage, la langue vaut pour la session */ }
}

export function t(key, ...args) {
  const v = DICTS[current][key] ?? fr[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}

export function numLocale() { return LANGS.find(l => l.id === current).num; }
export function dateLocale() { return LANGS.find(l => l.id === current).date; }
